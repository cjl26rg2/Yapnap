// Packs the PNG icons in src/art into src/art.js, as data URIs the chat page and the settings panel can use.
// Run with: node build/pack-art.js   (run again after any change to src/art)
const fs = require('node:fs');
const path = require('node:path');

const DIR = path.join(__dirname, '..', 'src', 'art');
const OUT = path.join(__dirname, '..', 'src', 'art.js');

const images = {};
for (const file of fs.readdirSync(DIR).filter((f) => f.endsWith('.png')).sort()) {
  const name = file.replace(/\.png$/, '');
  images[name] = 'data:image/png;base64,' + fs.readFileSync(path.join(DIR, file)).toString('base64');
}

const body = [
  '// Generated by build/pack-art.js from src/art. Do not edit by hand.',
  '(function () {',
  "  'use strict';",
  "  var root = typeof window !== 'undefined' ? window : globalThis;",
  '  if (root.YAPNAP_ART) return;',
  '  var images = ' + JSON.stringify(images) + ';',
  '  root.YAPNAP_ART = {',
  '    /** The image for a name such as "badge-owner", "cat-messages" or "ui-search". Empty string if unknown. */',
  "    src: function (name) { return Object.prototype.hasOwnProperty.call(images, name) ? images[name] : ''; },",
  '    names: Object.keys(images)',
  '  };',
  '})();',
  ''
].join('\n');

fs.writeFileSync(OUT, body);
console.log(`Packed ${Object.keys(images).length} images into src/art.js (${(body.length / 1024).toFixed(0)} KB)`);
